#!/usr/bin/env python3
"""Reproduce R9 review additions from preserved compact records, entirely offline.

No model execution, new bootstrap, new quality decisions, or calibration fitting.
Current YOLOv7 numeric quality is unavailable; historical AP is not promoted to
validation of the new implementation. Existing calibration files remain unchanged.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

LABEL = {
    "mobilenet_v3_large": "MobileNet-V3-L", "regnet_x_1_6gf": "RegNet-X",
    "resnet50": "ResNet-50", "yolo11l": "YOLO11l", "yolo26m": "YOLO26m",
    "yolo26s": "YOLO26s", "yolov7_paper": "YOLOv7",
}


def read(path):
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def write(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(dict.fromkeys(k for row in rows for k in row))
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def quality_for(row, quality):
    backend = row["split_backend"].removesuffix("_to_trt")
    found = [q for q in quality if
             (q["model_id"], q["setup_id"], q["case_id"], q["backend"], q["variant"]) ==
             (row["model_id"], row["setup_id"], row["case_id"], backend, "split")]
    assert len(found) == 1, (row["model_id"], row["setup_id"], row["case_id"], len(found))
    return found[0]


def table(path, caption, label, columns, header, rows, wide=False):
    env = "table*" if wide else "table"
    text = [r"% Generated by analysis/build_review_additions.py; do not edit.",
            rf"\begin{{{env}}}[t]", r"\centering\small",
            r"\setlength{\tabcolsep}{3pt}", rf"\caption{{{caption}}}",
            rf"\label{{{label}}}", rf"\begin{{tabular}}{{{columns}}}",
            r"\toprule", " & ".join(header) + r"\\", r"\midrule"]
    text += [" & ".join(row) + r"\\" for row in rows]
    text += [r"\bottomrule", r"\end{tabular}", rf"\end{{{env}}}", ""]
    path.write_text("\n".join(text))


def build(root, output_root, generated_root):
    a = root / "analysis"
    output = output_root
    output.mkdir(parents=True, exist_ok=True)
    sections = output / "sections"
    sections.mkdir(parents=True, exist_ok=True)
    paths = {
        "headlines": generated_root / "best_cases_output/top2_per_model_fastest_full_native_speedup.csv",
        "all_cases": generated_root / "best_cases_output/fastest_full_all_cases.csv",
        "quality": a / "evidence/tables/quality_effects.csv",
        "native": a / "runner_sources/native_cases.csv",
        "energy_metadata": a / "evidence/tables/energy_cases.csv",
        "energy_repeats": a / "best_cases_inputs/energy_repeats.csv",
        "reported": a / "reported_update/reported_results.csv",
        "calibration_sources": a / "review_inputs/calibration_sources.json",
    }
    heads, all_cases, quality = (read(paths[k]) for k in ("headlines", "all_cases", "quality"))
    native = {r["case_uid"]: r for r in read(paths["native"])}
    energy_meta = {r["case_uid"]: r for r in read(paths["energy_metadata"])}
    reported = {(r["setup"], r["case"], r["backend"]): r for r in read(paths["reported"])}
    assert len(heads) == 14 and len(all_cases) == 204

    ereps = defaultdict(list)
    for r in read(paths["energy_repeats"]):
        ereps[r["case_uid"]].append(r)
    energy = {}
    for uid, reps in ereps.items():
        assert len(reps) == 3
        rates = [float(r["completed_count"]) / float(r["active_duration_s"]) for r in reps]
        joules = [float(r["energy_j"]) / float(r["completed_count"]) for r in reps]
        assert all(math.isclose(j, float(r["recomputed_j_per_task"]), rel_tol=1e-12)
                   for j, r in zip(joules, reps))
        energy[uid] = {
            "energy_window_fps": statistics.mean(rates),
            "j_per_task": statistics.mean(joules),
            "duration_s_mean": statistics.mean(float(r["active_duration_s"]) for r in reps),
            "duration_s_min": min(float(r["active_duration_s"]) for r in reps),
            "duration_s_max": max(float(r["active_duration_s"]) for r in reps),
        }

    quality_rows, evidence = [], []
    for h in heads:
        q = quality_for(h, quality)
        is_report = h["model_id"] == "yolov7_paper"
        report = reported.get((h["setup_id"], h["case_id"], h["split_backend"]), {})
        n = native.get(h["split_native_uid"], {})
        e = energy_meta.get(h["split_energy_uid"], {})
        qr = {k: h[k] for k in ("model_id", "setup_id", "case_id", "model_rank")}
        qr.update(
            archived_quality_id=q["quality_id"],
            quality_scope="reported_label_only_current_implementation" if is_report else "archived_dataset_quality",
            metric=q["metric"], current_quality_label=h["split_accuracy_class"],
            candidate_score="NA" if is_report else float(q["candidate"]),
            cpu_reference_score="NA" if is_report else float(q["reference"]),
            delta_pp="NA" if is_report else 100 * float(q["delta"]),
            delta_ci_low_pp="NA" if is_report else 100 * float(q["ci_low"]),
            delta_ci_high_pp="NA" if is_report else 100 * float(q["ci_high"]),
            relative_loss="NA" if is_report else float(q["relative_loss"]),
            relative_loss_ci_low="NA" if is_report else float(q["relative_loss_ci_low"]),
            relative_loss_ci_high="NA" if is_report else float(q["relative_loss_ci_high"]),
            confidence_level="NA" if is_report else float(q["confidence_level"]),
            N="NA" if is_report else int(q["N"]),
            B="NA" if is_report else int(q["B"]),
            seed="NA" if is_report else int(q["seed"]),
            threshold_rule="point_estimate_relative_loss_le_0.05",
            ci_crosses_five_percent="NA" if is_report else
                float(q["relative_loss_ci_low"]) <= .05 <= float(q["relative_loss_ci_high"]),
        )
        quality_rows.append(qr)
        evidence.append({
            "model_id": h["model_id"], "setup_id": h["setup_id"], "case_id": h["case_id"],
            "model_rank": h["model_rank"], "split_backend": h["split_backend"],
            "baseline_backend": h["baseline_backend"], "semantic_pair_id": h["evidence_id"],
            "semantic_pair_scope": "archived_pair_identity_retained_for_report_overlay" if is_report
                else "archived_semantic_comparability_record",
            "performance_case_id": h["split_native_uid"],
            "baseline_performance_case_id": h["baseline_native_uid"],
            "performance_source": h["performance_source"],
            "performance_repeat_source": "analysis/reported_update/reported_results.csv" if is_report
                else "analysis/best_cases_inputs/performance_repeats.csv",
            "current_report_record_id": report.get("record_id", ""),
            "report_sha256": report.get("source_sha256", ""),
            "report_source_line": report.get("source_line", ""),
            "report_quality_source_line": report.get("quality_source_line", ""),
            "quality_record_id": "" if is_report else q["quality_id"],
            "historical_quality_record_id": q["quality_id"],
            "quality_scope": qr["quality_scope"],
            "quality_source": "analysis/reported_update/RESULT_REPORT.txt" if is_report
                else "analysis/evidence/tables/quality_effects.csv",
            "current_numeric_quality_available": not is_report,
            "native_command_sha256": "" if is_report else n.get("command_sha256", ""),
            "command_hash_scope": "unavailable_in_current_report" if is_report else "archived_command_contract",
            "endpoint_id": h["endpoint_id"],
            "endpoint_id_scope": "archived_endpoint_identity_not_new_contract_verification" if is_report
                else "archived_endpoint_contract",
            "energy_case_id": "" if is_report else h["split_energy_uid"],
            "baseline_energy_case_id": "" if is_report else h["baseline_energy_uid"],
            "energy_available": not is_report,
            "calibration_sha256": "" if is_report else e.get("calibration_sha256", ""),
            "decoder_sha256": "" if is_report else e.get("decoder_sha256", ""),
            "nms_sha256": "" if is_report else e.get("nms_sha256", ""),
            "compiled_artifact_sha256": "",
            "compiled_artifact_hash_scope": "not_available_in_compact_headline_projection",
            "raw_artifacts_independently_reverified": False,
        })
    write(output / "quality_highlights.csv", quality_rows)
    write(output / "headline_evidence.csv", evidence)
    tex = []
    for q in quality_rows:
        if q["quality_scope"] == "reported_label_only_current_implementation":
            values = ["NA", "NA", "NA", "NA", "reported close"]
        else:
            values = [f'{100*q["cpu_reference_score"]:.2f}', f'{100*q["candidate_score"]:.2f}',
                      f'{q["delta_pp"]:+.2f}',
                      f'[{q["delta_ci_low_pp"]:+.2f}, {q["delta_ci_high_pp"]:+.2f}]',
                      f'{100*q["relative_loss"]:.2f}']
        metric_label = "Top1" if q["metric"] == "Top1" else r"AP$_{50:95}$"
        tex.append([LABEL[q["model_id"]], q["setup_id"]+"/"+q["case_id"], metric_label] + values)
    table(sections / "quality_highlights_table.tex",
          r"Task quality of the fourteen throughput-ranked headline configurations. Scores use a 0--100 scale; "
          r"absolute differences and their intervals are in points, and relative loss is in percent. "
          r"Intervals are archived paired 95\% bootstrap intervals over 5,000 examples "
          r"(1,000 replicates). Admission uses the point estimate of relative loss, with a 5\% tolerance; an interval "
          r"may cross that threshold. Current YOLOv7 results supply reported reference-close labels but no new "
          r"dataset validation, so numeric fields are NA. Historical quality is not relabelled as validation of "
          r"the new implementation.",
          "tab:quality_highlights", "lllrrrlr",
          ["Model", "Setup/cut", "Metric", "CPU", "Split", r"$\Delta$", r"95\% CI of $\Delta$", r"Loss (\%)"], tex, True)

    available = [r for r in all_cases if r["energy_available"] == "True"]
    assert len(available) == 195
    fixed_full_max_loss = max(float(r["baseline_quality_relative_loss"]) for r in available)
    assert fixed_full_max_loss < .01
    sensitivity = []
    for tolerance in (.01, .02, .05):
        eligible = [r for r in available if r["semantic_comparable"] == "True"
                    and float(r["split_quality_relative_loss"]) <= tolerance
                    and float(r["baseline_quality_relative_loss"]) <= tolerance]
        sensitivity.append({
            "relative_loss_tolerance": tolerance, "models": 6,
            "available_split_cases": len(available), "eligible_cases": len(eligible),
            "faster_native": sum(float(r["native_speedup"]) > 1 for r in eligible),
            "lower_energy": sum(float(r["efficiency_gain"]) > 1 for r in eligible),
            "improve_both": sum(float(r["native_speedup"]) > 1 and float(r["efficiency_gain"]) > 1 for r in eligible),
            "baseline_rule": "fastest_Native_Full_chosen_before_filter_and_held_fixed",
            "decision_rule": "point_estimate_not_confidence_bound",
            "fixed_full_max_relative_loss": fixed_full_max_loss,
        })
    assert [r["eligible_cases"] for r in sensitivity] == [105, 136, 178]
    assert [r["improve_both"] for r in sensitivity] == [31, 51, 67]
    write(output / "quality_tolerance.csv", sensitivity)
    table(sections / "quality_tolerance_table.tex",
          r"Post-hoc sensitivity to relative task-quality loss tolerance, over 195 split configurations from "
          r"the six models with current energy. The Native-FPS-selected Full and local semantic requirement "
          r"are held fixed; all eighteen selected Fulls also satisfy the 1\% tolerance. Counts require both "
          r"quality point estimates within tolerance and use separate Native-performance and energy "
          r"measurements; they do not redefine archived quality labels. YOLOv7 is excluded.",
          "tab:quality_tolerance", "rrrrr",
          ["Tolerance", "Eligible", "Faster", "Less energy", "Both"],
          [[f'{100*r["relative_loss_tolerance"]:.0f}'+r"\%", str(r["eligible_cases"]),
            str(r["faster_native"]), str(r["lower_energy"]), str(r["improve_both"])] for r in sensitivity])

    eligible = [r for r in available if r["fastest_full_eligible"] == "True"]
    long_rows, groups = [], defaultdict(list)
    for r in eligible:
        es, ef = energy[r["split_energy_uid"]], energy[r["baseline_energy_uid"]]
        assert math.isclose(es["j_per_task"], float(r["split_j_per_task"]), rel_tol=1e-12)
        lr = {k: r[k] for k in ("model_id", "setup_id", "case_id", "baseline_backend")}
        lr.update(native_speedup=float(r["native_speedup"]),
                  energy_window_speedup=es["energy_window_fps"]/ef["energy_window_fps"],
                  split_native_fps=float(r["split_native_fps"]),
                  split_energy_window_fps=es["energy_window_fps"],
                  baseline_energy_window_fps=ef["energy_window_fps"],
                  split_duration_s_mean=es["duration_s_mean"],
                  baseline_duration_s_mean=ef["duration_s_mean"],
                  split_duration_s_min=es["duration_s_min"], split_duration_s_max=es["duration_s_max"],
                  split_energy_uid=r["split_energy_uid"], baseline_energy_uid=r["baseline_energy_uid"],
                  lower_energy=float(r["efficiency_gain"]) > 1)
        long_rows.append(lr)
        groups[(r["model_id"], r["setup_id"])].append(lr)
    group_rows = []
    for (model, setup), rows in sorted(groups.items()):
        nbest = max(rows, key=lambda r: r["split_native_fps"])
        ebest = max(rows, key=lambda r: r["split_energy_window_fps"])
        group_rows.append(dict(model_id=model, setup_id=setup, n=len(rows),
                               native_best_case=nbest["case_id"], energy_window_best_case=ebest["case_id"],
                               same_winner=nbest["case_id"] == ebest["case_id"]))
    assert len(groups) == 18 and sum(r["same_winner"] for r in group_rows) == 16
    write(output / "long_window_cases.csv", long_rows)
    write(output / "long_window_groups.csv", group_rows)
    three = [next(r for r in long_rows if
                  (r["model_id"], r["setup_id"], r["case_id"]) ==
                  (h["model_id"], h["setup_id"], h["case_id"]))
             for h in heads if h["model_id"] in list(LABEL)[:3] and h["model_rank"] == "1"]
    write(output / "long_window_highlights.csv", three)
    table(sections / "long_window_table.tex",
          r"Longer-window rate sensitivity for the leading H10 classification configurations. $S_N$ uses "
          r"the three 1,000-task Native repetitions; $S_E$ uses mean per-repeat $N/T$ in the separate "
          r"energy runs. The same Native-selected Full identity is retained. Mean split-window durations "
          r"are shown; these are existing measurements, not a new thermal or controlled-duration experiment.",
          "tab:long_window", "lrrr",
          ["Configuration", r"$S_N$", r"$S_E$", r"Window (s)"],
          [[LABEL[r["model_id"]]+"/"+r["case_id"], f'{r["native_speedup"]:.2f}'+r"$\times$",
            f'{r["energy_window_speedup"]:.2f}'+r"$\times$", f'{r["split_duration_s_mean"]:.2f}'] for r in three])
    long_summary = dict(eligible_cases=len(long_rows), groups=len(groups),
                        same_winner_groups=sum(r["same_winner"] for r in group_rows),
                        faster_native=sum(r["native_speedup"] > 1 for r in long_rows),
                        faster_energy_window=sum(r["energy_window_speedup"] > 1 for r in long_rows),
                        both_native_and_energy=sum(r["native_speedup"] > 1 and r["lower_energy"] for r in long_rows),
                        both_energy_window_and_energy=sum(r["energy_window_speedup"] > 1 and r["lower_energy"] for r in long_rows),
                        fixed_reference="Native-FPS-selected Full, held fixed for longer-window ratio")
    assert (long_summary["faster_native"], long_summary["faster_energy_window"],
            long_summary["both_native_and_energy"], long_summary["both_energy_window_and_energy"]) == (82, 85, 67, 70)
    dump(output / "long_window_summary.json", long_summary)

    cal_manifest = json.loads(paths["calibration_sources"].read_text())
    calibration = []
    for src in cal_manifest["files"]:
        path = root / src["bundle_path"]
        assert sha(path) == src.get("curated_sha256", src["sha256"])
        assert path.stat().st_size == src.get("curated_bytes", src["bytes"])
        cal = json.loads(path.read_text())
        fit = cal["fit"]
        bound = [r for r in energy_meta.values() if r["setup_id"] == src["setup"] and r["model_id"] != "yolov7_paper"]
        assert bound and all(r["calibration_sha256"] == src["sha256"] for r in bound)
        calibration.append(dict(
            setup=src["setup"], setup_id=cal["setup_id"], source_path=src["bundle_path"],
            source_sha256=src["sha256"], current_energy_cases=len(bound),
            sample_rate_sps=cal["configuration_projection"]["energy_defaults"]["sample_rate"],
            measurement_scope=cal["measurement_scope"], load_connection=cal["load_connection"],
            scale_factor=fit["scale_factor"], fit_model=fit["model"],
            fit_intercept="fixed_zero_not_estimated",
            reference_currents_a=json.dumps([p["reference_current_a"] for p in fit["point_results"]]),
            reference_voltages_v=json.dumps([p["reference_voltage_v"] for p in fit["point_results"]]),
            reference_powers_w=json.dumps([p["reference_power_w"] for p in fit["point_results"]]),
            max_fit_residual_pct=fit["max_fit_residual_pct"], point_spread_pct=fit["point_spread_pct"],
            idle_drift_w=fit["idle_drift_w"], stored_quality_gate_pass=cal["quality_gate"]["pass"],
            stored_warning_reasons=";".join(cal["quality_gate"]["warning_reasons"]),
            calibration_started_at=cal["started_at"], calibration_finished_at=cal["finished_at"],
            calibration_instrument_uncertainty="not_quantified_in_supplied_record",
            interpretation="fit residuals are not a complete propagated measurement uncertainty",
        ))
    assert sum(r["current_energy_cases"] for r in calibration) == 231
    write(output / "calibration_summary.csv", calibration)
    dump(output / "calibration_summary.json", {
        "schema": "mlsys_review_calibration_summary_v1", "records": calibration,
        "scope": "Existing full-system DC-input scale calibration; no idle subtraction in task energy.",
        "uncertainty": "No complete traceable sensor/reference uncertainty budget is supplied. Fit residuals, point spread and repeat variability are distinct.",
        "ratio_cancellation": "A shared multiplicative scale cancels in same-setup split/Full energy ratios; nonlinear or load-dependent errors need not cancel.",
    })
    sources = [{"path": ("generated/" + str(path.relative_to(generated_root)))
                if path.is_relative_to(generated_root) else str(path.relative_to(root)),
                "sha256": sha(path)} for path in paths.values()]
    validation = dict(schema="mlsys_r9_review_additions_v1", pass_all=True,
                      headline_cases=len(heads), numeric_quality_headlines=12,
                      report_only_quality_headlines=2, calibration_files_verified=3,
                      current_energy_cases=231, quality_tolerance=sensitivity,
                      longer_windows=long_summary, sources=sources,
                      new_inference=0, new_bootstrap=0, new_calibration_fits=0,
                      compiled_artifact_hashes_invented=0)
    dump(output / "review_validation.json", validation)
    print(json.dumps({k: validation[k] for k in
                      ("pass_all", "headline_cases", "numeric_quality_headlines", "report_only_quality_headlines",
                       "calibration_files_verified", "current_energy_cases", "longer_windows")}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--generated-root", type=Path, required=True)
    args = parser.parse_args()
    build(args.root.resolve(), args.output_root.resolve(), args.generated_root.resolve())
