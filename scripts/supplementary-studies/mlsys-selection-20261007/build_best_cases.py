def fastest_full_analysis(pairs, output):
    """Select the fastest Full before filtering; current energy is optional."""
    grouped = defaultdict(list)
    for row in pairs:
        grouped[configuration(row)].append(row)
    all_cases, energy_sensitivity = [], []
    for config, candidates in sorted(grouped.items()):
        assert len(candidates) == 2 and {r['baseline_kind'] for r in candidates} == {'vendor_full', 'tensorrt_full'}
        selected = sorted(candidates, key=lambda r: (-r['baseline_native_fps'], r['baseline_backend']))[0]
        eligible = selected['semantic_comparable'] and selected['split_accuracy_class'] == 'reference_close'
        exclusion = '' if eligible else ('selected_fastest_full_semantics' if not selected['semantic_comparable'] else 'split_quality_loss')
        row = dict(fastest_full_eligible=eligible, exclusion_reason=exclusion, **selected)
        close(row['native_speedup'], row['split_native_fps'] / max(r['baseline_native_fps'] for r in candidates))
        all_cases.append(row)
        erows = [r for r in candidates if r['energy_available']]
        energy_best = min(erows, key=lambda r: (r['baseline_j_per_task'], r['baseline_backend'])) if erows else None
        if energy_best:
            close(row['efficiency_gain'], row['baseline_j_per_task'] / row['split_j_per_task'])
        energy_sensitivity.append(dict(model_id=selected['model_id'], setup_id=selected['setup_id'], case_id=selected['case_id'],
            split_native_uid=selected['split_native_uid'], split_accuracy_class=selected['split_accuracy_class'],
            fastest_full_backend=selected['baseline_backend'], fastest_full_semantic=selected['semantic_comparable'],
            fastest_full_eligible=eligible, native_speedup_over_fastest_full=selected['native_speedup'],
            energy_available=selected['energy_available'], efficiency_over_fastest_full=selected['efficiency_gain'],
            energy_best_full_backend=energy_best['baseline_backend'] if energy_best else 'NA',
            energy_best_full_j_per_task=energy_best['baseline_j_per_task'] if energy_best else 'NA',
            energy_best_full_semantic=energy_best['semantic_comparable'] if energy_best else False,
            energy_best_full_accuracy_class=energy_best['baseline_accuracy_class'] if energy_best else 'NA',
            energy_best_full_eligible=bool(energy_best and energy_best['semantic_comparable'] and energy_best['split_accuracy_class']=='reference_close'),
            efficiency_over_energy_best_full=energy_best['efficiency_gain'] if energy_best else 'NA',
            full_identity_changes=selected['baseline_backend'] != energy_best['baseline_backend'] if energy_best else 'NA',
            split_j_per_task=selected['split_j_per_task']))
    eligible = [r for r in all_cases if r['fastest_full_eligible']]
    energy_eligible = [r for r in eligible if r['energy_available']]
    assert len(all_cases) == 204 and len(eligible) == 187 and len(energy_eligible) == 178
    assert Counter(r['exclusion_reason'] for r in all_cases) == {'':187, 'split_quality_loss':17}
    write(output/'fastest_full_all_cases.csv',all_cases)
    write(output/'fastest_full_eligible_cases.csv',eligible)
    write(output/'energy_best_full_sensitivity.csv',energy_sensitivity)
    selections = {}
    for metric in ('native_speedup','efficiency_gain'):
        chosen=[]
        for model in MODELS:
            candidates=ranked([r for r in eligible if r['model_id']==model],metric)
            if metric=='efficiency_gain' and model==INVESTIGATED_MODEL:
                assert not candidates
                continue
            assert len(candidates)>=2
            chosen.extend(dict(model_rank=i,**r) for i,r in enumerate(candidates[:2],1))
        expected=14 if metric=='native_speedup' else 12
        assert len(chosen)==len({configuration(r) for r in chosen})==expected
        assert all(r[metric]>1 for r in chosen)
        selections[metric]=chosen
        write(output/f'top2_per_model_fastest_full_{metric}.csv',chosen)
    joint_sensitivity=[r for r in energy_sensitivity if r['energy_available'] and r['fastest_full_eligible'] and r['energy_best_full_eligible']]
    summary=dict(reference_policy='same model/setup; fastest measured Full FPS selected before quality or semantic filtering; no weaker-baseline fallback',
        speedup_definition='Native split median FPS / maximum Native Full median FPS',
        energy_gain_definition='Full J/task / split J/task using the same FPS-selected Full; separate energy windows; unavailable current energy is NA',
        main_selection_policy='two distinct configurations per model ranked by Native speedup, with energy where available',
        candidate_configurations=204,eligible_configurations=187,energy_available_configurations=195,energy_eligible_configurations=178,
        selected_full_backend_counts=dict(Counter(r['baseline_kind'] for r in all_cases)),
        eligible_full_backend_counts=dict(Counter(r['baseline_kind'] for r in eligible)),
        excluded_for_fastest_full_semantics=0,excluded_for_split_quality=17,
        eligible_full_accuracy_loss=sum(r['baseline_accuracy_class']=='accuracy_loss' for r in eligible),
        eligible_both_reference_close=sum(r['both_reference_close'] for r in eligible),
        faster_native=sum(r['native_speedup']>1 for r in eligible),
        lower_energy_same_full=sum(r['efficiency_gain']>1 for r in energy_eligible),
        joint_native_speed_and_energy=sum(r['native_speedup']>1 and r['efficiency_gain']>1 for r in energy_eligible),
        main_rows=14,main_rows_energy_available=sum(r['energy_available'] for r in selections['native_speedup']),
        main_rows_joint_positive=sum(r['energy_available'] and r['efficiency_gain']>1 and r['native_speedup']>1 for r in selections['native_speedup']),
        main_full_accuracy_loss=sum(r['baseline_accuracy_class']=='accuracy_loss' for r in selections['native_speedup']),
        max_native_speedup=max(r['native_speedup'] for r in eligible),
        max_energy_efficiency_same_full=max(r['efficiency_gain'] for r in energy_eligible),
        per_model=[dict(model_id=model,eligible=sum(r['model_id']==model for r in eligible),
            energy_available=sum(r['model_id']==model for r in energy_eligible),
            faster_native=sum(r['model_id']==model and r['native_speedup']>1 for r in eligible),
            lower_energy_same_full=sum(r['model_id']==model and r['efficiency_gain']>1 for r in energy_eligible),
            joint=sum(r['model_id']==model and r['native_speedup']>1 and r['efficiency_gain']>1 for r in energy_eligible)) for model in MODELS],
        energy_best_sensitivity=dict(eligible_fastest_full_cases=178,
            changed_reference_among_eligible=sum(r['fastest_full_eligible'] and r['full_identity_changes'] is True for r in energy_sensitivity),
            comparable_both_baseline_choices=len(joint_sensitivity),
            lower_energy_than_energy_best_full=sum(r['efficiency_over_energy_best_full']>1 for r in joint_sensitivity),
            faster_than_fastest_full_and_lower_energy_than_energy_best_full=sum(r['native_speedup_over_fastest_full']>1 and r['efficiency_over_energy_best_full']>1 for r in joint_sensitivity)),
        modality_caution='Native performance and energy-window throughput are separate measurements; missing current energy is excluded, never combined with current FPS',
        reported_update=dict(model_id=INVESTIGATED_MODEL,split_cases=9,full_cases=6,current_energy_cases=0,
            verification_scope='report_transcription_and_arithmetic_only; source archive unavailable',
            source='analysis/reported_update/RESULT_REPORT.txt',source_sha256=next(r['report_sha256'] for r in pairs if r['report_sha256'])))
    assert (summary['faster_native'],summary['lower_energy_same_full'],summary['joint_native_speed_and_energy'])==(86,102,67)
    (output/'fastest_full_summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    (output/'best_cases_table.tex').write_text(fastest_full_table(selections['native_speedup']))
    energy_parts=[r'% Generated by analysis/build_best_cases.py.',r'\begin{table*}[t]',r'\centering',r'\caption{Two energy-efficiency leaders per model relative to the fastest Full selected by completed-task throughput. Energy is measured separately; the FPS-selected Full identity is held fixed. YOLOv7 has no current energy ranking.}',r'\label{tab:energy-leaders}',r'\small',r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lllrrrr@{}}',r'\toprule',r'Model & Setup/cut & Full & Full J/task & Split J/task & $G_\eta$ & Saving\\',r'\midrule']
    for r in selections['efficiency_gain']:
        energy_parts.append(' & '.join([MODELS[r['model_id']] if r['model_rank']==1 else '',r['setup_id']+'/'+r['case_id'],'TRT' if r['baseline_kind']=='tensorrt_full' else 'Acc.',f"{r['baseline_j_per_task']:.4f}",f"{r['split_j_per_task']:.4f}",f"{r['efficiency_gain']:.2f}"+r'$\times$',f"{r['energy_saving_pct']:.2f}"+r'\%'])+r'\\')
    energy_parts += [r'YOLOv7 & \multicolumn{6}{l}{NA: energy not available}\\',r'\bottomrule',r'\end{tabular*}',r'\end{table*}','']
    (output/'energy_leaders_table.tex').write_text('\n'.join(energy_parts))
    return summary


def apply_reported_overlay(pairs, overlay_path):
    """Replace current YOLOv7 FPS; never substitute historical energy."""
    report_path=overlay_path.parent/'RESULT_REPORT.txt'
    report_digest=hashlib.sha256(report_path.read_bytes()).hexdigest()
    overlay=read(overlay_path)
    assert len(overlay)==15 and {r['source_sha256'] for r in overlay}=={report_digest}
    omap={(r['setup'],r['backend'],r['case']):r for r in overlay}
    assert len(omap)==15
    energy_fields=['split_j_per_task','baseline_j_per_task','split_tasks_per_joule','baseline_tasks_per_joule','efficiency_gain','energy_saving_pct','efficiency_gain_repeat9_min','efficiency_gain_repeat9_max']
    for row in pairs:
        row.update(energy_available=True,performance_source='frozen_repeat_evidence',report_sha256='',verification_scope='recomputed_from_frozen_repeats',split_performance_cohort=row['cohort'],baseline_performance_cohort='base')
        if row['model_id']!=INVESTIGATED_MODEL:
            continue
        sr=omap[(row['setup_id'],row['split_backend'],row['case_id'])]
        fr=omap[(row['setup_id'],row['baseline_backend'],'full')]
        sv=[float(sr[f'fps_{i}']) for i in (1,2,3)]
        fv=[float(fr[f'fps_{i}']) for i in (1,2,3)]
        close(statistics.median(sv),sr['fps_median']);close(statistics.median(fv),fr['fps_median'])
        assert sr['energy_status']==fr['energy_status']=='not_measured'
        row.update(split_native_uid='report:'+sr['record_id'],baseline_native_uid='report:'+fr['record_id'],
            split_energy_uid='NA',baseline_energy_uid='NA',split_native_fps=statistics.median(sv),baseline_native_fps=statistics.median(fv),
            native_speedup=statistics.median(sv)/statistics.median(fv),
            native_speedup_repeat9_min=min(s/f for s in sv for f in fv),native_speedup_repeat9_max=max(s/f for s in sv for f in fv),
            split_accuracy_class=sr['quality_status'],baseline_accuracy_class=fr['quality_status'],
            both_reference_close=sr['quality_status']==fr['quality_status']=='reference_close',
            split_quality_relative_loss='NA',baseline_quality_relative_loss='NA',
            energy_available=False,performance_source='analysis/reported_update/RESULT_REPORT.txt',report_sha256=report_digest,
            verification_scope=sr['verification_scope'],split_performance_cohort=sr['performance_cohort'],baseline_performance_cohort=fr['performance_cohort'],
            runtime_conditions_comparable='report_metadata_only_not_independently_verified')
        for field in energy_fields:row[field]='NA'
    assert sum(not r['energy_available'] for r in pairs)==18
    return dict(path=str(overlay_path.name),source_sha256=report_digest,rows=15,split_rows=9,full_rows=6,
                verification_scope='report_transcription_and_arithmetic_only',measurement_date='not_specified_in_supplied_report')


def build(inputs, output, overlay_path):
    output.mkdir(parents=True, exist_ok=True)
    provenance = json.loads((inputs / "provenance.json").read_text())
    for name, spec in provenance.items():
        assert hashlib.sha256((inputs / name).read_bytes()).hexdigest() == spec["projection_sha256"], name

    native = read(inputs / "native_cases.csv")
    energy = read(inputs / "energy_cases.csv")
    performance_repeats = read(inputs / "performance_repeats.csv")
    energy_repeats = read(inputs / "energy_repeats.csv")
    admissions = read(inputs / "pair_admissions.csv")
    nmap, emap = index(native), index(energy)
    assert nmap.keys() == emap.keys()
    nr, er = defaultdict(list), defaultdict(list)
    for row in performance_repeats:
        assert float(row["completed_count"]) == 1000
        fps = float(row["completed_count"]) / float(row["makespan_s"])
        close(fps, row["recomputed_fps"])
        nr[row["case_uid"]].append((int(row["repetition"]), fps))
    for row in energy_repeats:
        n, e, t = (float(row[key]) for key in ("completed_count", "energy_j", "active_duration_s"))
        assert min(n, e, t) > 0
        close(e / n, row["recomputed_j_per_task"])
        er[row["case_uid"]].append((int(row["repetition"]), e / n, n / t, e / t))
    for row in native:
        rr = nr[row["case_uid"]]
        assert len(rr) == 3 and {x[0] for x in rr} == {0, 1, 2}
        close(row["fps"], statistics.median(x[1] for x in rr))
    for row in energy:
        rr = er[row["case_uid"]]
        assert len(rr) == 3 and {x[0] for x in rr} == {0, 1, 2}
        close(row["energy_per_task_j"], statistics.mean(x[1] for x in rr))
        # This contextual copy is rounded in some original energy reports.
        assert math.isclose(float(row["performance_fps"]), float(nmap[ident(row)]["fps"]), rel_tol=1e-8, abs_tol=1e-6)

    pairs = []
    assert len(index(admissions, lambda r: tuple(r[k] for k in ("cohort", "model_id", "case_id", "setup_id", "split_backend", "baseline_backend")))) == 408
    for a in admissions:
        skey = tuple(a[k] for k in ("cohort", "model_id", "case_id", "setup_id")) + (a["split_backend"],)
        fkey = ("base", a["model_id"], "full", a["setup_id"], a["baseline_backend"])
        ns, nf, es, ef = nmap[skey], nmap[fkey], emap[skey], emap[fkey]
        assert a["descriptive_comparable"] == "True"
        for key in ("task", "endpoint_id", "physical_scope", "window", "calibration_sha256"):
            assert es[key] == ef[key], (a["evidence_id"], key)
        for r in (ns, nf):
            assert r["task"] == es["task"] and r["endpoint_id"] == es["endpoint_id"]
        assert es["precision"] == a["precision"]
        if a["split_boundary_precision"]:
            assert es["precision"] == a["split_boundary_precision"]
        assert ef["precision"] == a["baseline_runtime_precision"]
        assert es["physical_scope"] == "full_system" and es["window"] == "command_window"
        assert es["calibration_sha256"] == a["energy_calibration_sha256"]
        sfps = statistics.median(x[1] for x in nr[ns["case_uid"]])
        ffps = statistics.median(x[1] for x in nr[nf["case_uid"]])
        sj = statistics.mean(x[1] for x in er[es["case_uid"]])
        fj = statistics.mean(x[1] for x in er[ef["case_uid"]])
        close(sj / fj, a["descriptive_energy_ratio"])
        speeds = [x[1] / y[1] for x in nr[ns["case_uid"]] for y in nr[nf["case_uid"]]]
        efficiencies = [y[1] / x[1] for x in er[es["case_uid"]] for y in er[ef["case_uid"]]]
        pair = {key: a[key] for key in ("evidence_id", "cohort", "model_id", "case_id", "setup_id", "split_backend", "baseline_backend", "baseline_kind")}
        pair.update(split_native_uid=ns["case_uid"], baseline_native_uid=nf["case_uid"],
                    split_energy_uid=es["case_uid"], baseline_energy_uid=ef["case_uid"],
                    split_boundary_precision=es["precision"], baseline_runtime_precision=ef["precision"],
                    endpoint_id=es["endpoint_id"], semantic_comparable=a["semantic_comparable"] == "True",
                    split_accuracy_class=es["accuracy_class"], baseline_accuracy_class=ef["accuracy_class"],
                    both_reference_close=es["accuracy_class"] == ef["accuracy_class"] == "reference_close",
                    split_quality_relative_loss=es["quality_relative_loss"], baseline_quality_relative_loss=ef["quality_relative_loss"],
                    split_native_fps=sfps, baseline_native_fps=ffps, native_speedup=sfps / ffps,
                    split_j_per_task=sj, baseline_j_per_task=fj, split_tasks_per_joule=1 / sj,
                    baseline_tasks_per_joule=1 / fj, efficiency_gain=fj / sj,
                    energy_saving_pct=100 * (1 - sj / fj), native_speedup_repeat9_min=min(speeds),
                    native_speedup_repeat9_max=max(speeds), efficiency_gain_repeat9_min=min(efficiencies),
                    efficiency_gain_repeat9_max=max(efficiencies),
                    split_runner=ns["source_runner"], baseline_runner=nf["source_runner"],
                    semantic_reason=a["reason"] or a["semantic_comparison_reasons"],
                    runtime_conditions_comparable=a["runtime_conditions_comparable"])
        close(pair["split_tasks_per_joule"] / pair["baseline_tasks_per_joule"], pair["efficiency_gain"])
        pairs.append(pair)
    overlay_provenance = apply_reported_overlay(pairs, overlay_path)
    pairs.sort(key=lambda r: r["evidence_id"])
    screened = [r for r in pairs if r["semantic_comparable"] and r["both_reference_close"]]
    per_model_eligible = [r for r in pairs if r["semantic_comparable"] and r["split_accuracy_class"] == "reference_close"]
    assert len(screened) == 327
    assert len(per_model_eligible) == 358
    assert len({configuration(r) for r in per_model_eligible}) == 187
    assert len({r["split_native_uid"] for r in pairs}) == 204
    assert len({r["baseline_native_uid"] for r in pairs}) == 42
    for rows in (pairs, screened):
        for metric in ("native_speedup", "efficiency_gain"):
            assert all(r[metric] > 1 for r in ranked(rows, metric)[:10])

    coverage = read(inputs / "coverage.csv")
    unsupported = read(inputs / "native_unsupported.csv")
    original_splits = [r for r in coverage if r["variant"] == "composed" and r["backend"] != "tensorrt"]
    controls = [r for r in coverage if r["variant"] == "composed" and r["backend"] == "tensorrt"]
    base = {split_ident(r) for r in native if r["execution_mode"] == "split" and r["cohort"] == "base"}
    aug = {split_ident(r) for r in native if r["cohort"] == "augmentation"}
    rejected = {split_ident(r) for r in unsupported}
    planned = {split_ident(r) for r in original_splits}
    assert len(original_splits) == len(planned) == 420
    assert len(base) == 192 and len(rejected) == 228 and not base & rejected
    assert base | rejected == planned and not aug & planned and len(aug) == 12
    assert {r["reason"] for r in unsupported} == {"part2_input_count_not_one"}
    assert Counter(r["status"] for r in original_splits) == {"completed": 359, "build_failed": 37, "policy_excluded": 24}
    assert len(controls) == 140 and {r["status"] for r in controls} == {"completed"}
    assert len(coverage) == 588
    counts = dict(models=len({r["model_id"] for r in original_splits}), setups=len({r["setup_id"] for r in original_splits}),
                  base_accelerator_gpu_split_identities=420, cuts_per_model_setup=20,
                  base_accelerator_gpu_status=dict(Counter(r["status"] for r in original_splits)),
                  additional_tensorrt_split_controls=140, historical_full_rows=28, total_coverage_rows=588,
                  total_coverage_status=dict(Counter(r["status"] for r in coverage)),
                  base_native_completed_splits=192, base_native_unsupported_splits=228,
                  additional_new_native_split_identities=12, native_completed_splits=204, native_unique_fulls=42,
                  native_cases=246, native_repetitions=738, energy_cases=231, energy_repetitions=693,
                  energy_split_cases=195, energy_full_cases=36, energy_comparison_pairs=390,
                  energy_semantic_pairs=sum(r["semantic_comparable"] and r["energy_available"] for r in pairs),
                  energy_semantic_and_both_reference_close_pairs=sum(r["semantic_comparable"] and r["both_reference_close"] and r["energy_available"] for r in pairs),
                  report_based_performance_cases=15, repeat_evidence_performance_cases=231,
                  split_full_comparison_pairs=408, semantic_pairs=sum(r["semantic_comparable"] for r in pairs),
                  semantic_and_both_reference_close_pairs=len(screened),
                  semantic_and_split_reference_close_pairs=len(per_model_eligible),
                  per_model_eligible_distinct_configurations=len({configuration(r) for r in per_model_eligible}))
    assert counts["models"] == 7 and counts["setups"] == 3
    for model in {r["model_id"] for r in original_splits}:
        for setup in {r["setup_id"] for r in original_splits}:
            assert len({r["case_id"] for r in original_splits if r["model_id"] == model and r["setup_id"] == setup}) == 20

    write(output / "best_cases_pairs.csv", pairs)
    summary = {}
    for scope, rows in (("screened", screened), ("unfiltered", pairs)):
        for metric in ("native_speedup", "efficiency_gain"):
            top = [dict(rank=i, **r) for i, r in enumerate(ranked(rows, metric)[:10], 1)]
            write(output / f"top10_{scope}_{metric}.csv", top)
            summary[scope + "_" + metric] = top[0]
    # Keep the semantic/quality screen; current FPS replaces report-covered cases and unavailable energy is excluded.
    (output / "global_top10_screened_table.tex").write_text(table(screened, True))
    selections, alternatives = {}, []
    for metric in ("native_speedup", "efficiency_gain"):
        selections[metric] = select_per_model(per_model_eligible, metric)
        write(output / f"top2_per_model_{metric}.csv", selections[metric])
        for chosen in selections[metric]:
            for row in [r for r in pairs if configuration(r) == configuration(chosen)]:
                alternatives.append(dict(objective=metric, model_rank=chosen["model_rank"],
                                         selected_reference=row["evidence_id"] == chosen["evidence_id"],
                                         main_table_eligible=row["semantic_comparable"] and row["split_accuracy_class"] == "reference_close", **row))
    assert len(alternatives) == 52
    write(output / "per_model_all_reference_comparisons.csv", alternatives)
    (output / "revision4_per_model_table.tex").write_text(per_model_table(selections, per_model_eligible))
    fastest_summary = fastest_full_analysis(pairs, output)
    (output / "supplement_best_cases.tex").write_text(table(pairs, False))
    validation = dict(status="PASS", counts=counts, maxima=summary,
                      fps_aggregation="median_of_three_native_completed_count_over_makespan_ratios",
                      energy_aggregation="mean_of_three_full_system_E_over_N_ratios",
                      efficiency_definition="tasks_per_joule_gain=Full_J_per_task/split_J_per_task",
                      screened_top10_quality_rule="reference_close_labels_on_both_sides; YOLOv7 labels from supplied report",
                      pair_admission="unchanged_local_semantic_comparable_projection",
                      top10_unit="split/reference_pair; shared Fulls not independent observations",
                      reported_overlay=overlay_provenance,
                      revision4_table=dict(rows_per_panel={"native_speedup":14,"efficiency_gain":12}, models=7, distinct_configurations_per_model=2,
                                      eligible_pairs=358, eligible_configurations=187,
                                      quality_rule="split_reference_close; Full accuracy_loss retained and explicitly marked",
                                      baseline_rule="maximal objective gain among locally semantically comparable Full references; other eligible Full ratio shown",
                                      excluded_other_reference_display="dash; original negative or missing semantics retained in alternate-reference CSV",
                                      maxima={m: max(r[m] for r in selections[m]) for m in selections},
                                      full_accuracy_loss_rows={m: sum(r["full_accuracy_loss"] for r in selections[m]) for m in selections}),
                      main_table=fastest_summary,
                      limitation="Native and Full runner differences are retained; gains are observed configuration effects, not isolated cut effects.")
    (output / "best_cases_validation.json").write_text(json.dumps(validation, indent=2) + "\n")
    print(json.dumps(dict(status="PASS", counts=counts,
                         maxima={k: {f: v[f] for f in ("model_id", "setup_id", "case_id", "baseline_kind", "native_speedup", "efficiency_gain", "energy_saving_pct")} for k, v in summary.items()}), indent=2))

