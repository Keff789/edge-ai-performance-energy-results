def configuration(row):
    """A split is distinct independently of which Full reference it uses."""
    return tuple(row[key] for key in ("model_id", "setup_id", "case_id", "split_backend", "split_boundary_precision", "endpoint_id"))


def select_per_model(eligible, metric):
    choices = {}
    for row in ranked(eligible, metric):
        choices.setdefault(configuration(row), row)
    selected = []
    for model in MODELS:
        candidates = ranked([r for r in choices.values() if r["model_id"] == model], metric)
        if metric == "efficiency_gain" and model == INVESTIGATED_MODEL:
            assert not candidates
            continue
        assert len(candidates) >= 2, (model, metric)
        for model_rank, row in enumerate(candidates[:2], 1):
            assert row[metric] > 1
            assert row[metric] == max(r[metric] for r in eligible if configuration(r) == configuration(row))
            selected.append(dict(model_rank=model_rank, full_accuracy_loss=row["baseline_accuracy_class"] == "accuracy_loss", **row))
    expected = 12 if metric == "efficiency_gain" else 14
    assert len(selected) == expected and len({configuration(r) for r in selected}) == expected
    return selected


