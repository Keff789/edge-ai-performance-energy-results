#!/usr/bin/env python3
"""Recompute and rank measured split/Full cases from compact frozen evidence.

No inference, fitting, new quality decisions, or cross-window energy estimates.
FPS is the median of three 1,000-task Native repetitions. J/task is the mean
of three E/N ratios from separate full-system energy measurement windows.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import statistics
from collections import Counter, defaultdict
from pathlib import Path


def read(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def write(path, rows):
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def ident(row):
    return tuple(row[key] for key in ("cohort", "model_id", "case_id", "setup_id", "backend"))


def split_ident(row):
    return tuple(row[key] for key in ("model_id", "case_id", "setup_id"))


def index(rows, key=ident):
    result = {}
    for row in rows:
        assert key(row) not in result, ("duplicate", key(row))
        result[key(row)] = row
    return result


def close(a, b):
    assert math.isclose(float(a), float(b), rel_tol=1e-10, abs_tol=1e-10), (a, b)


def ranked(rows, field):
    # Tie-breaking is deterministic and cannot alter unequal numeric ranks.
    return sorted([r for r in rows if isinstance(r[field], (int, float)) and math.isfinite(r[field])], key=lambda r: (-r[field], r["model_id"], r["setup_id"], r["case_id"], r["baseline_backend"]))


