#!/usr/bin/env python3
"""Read-only verification and exact reconstruction of the R20 evidence projections.

Without --archive, verify all bundled SHA-256 values and selected value contracts.
With --archive PATH, also verify the original ZIP and source members, reconstruct
all projections in memory, and compare every generated byte. No files are written.
This program uses only the Python standard library and never accesses hardware.
"""
from pathlib import Path
import argparse
import collections
import gzip
import hashlib
import json
import zipfile

ROOT = Path(__file__).resolve().parent
MODELS = {"yolo11l", "yolo26m", "yolo26s", "yolov7_paper"}
CASE_UIDS = {
    "native|yolov7_paper|H8|hailo8_to_trt|b066",
    "native|yolov7_paper|H8|native_full_hailo8|full",
    "native|yolov7_paper|H8|native_full_tensorrt|full",
}

def digest(data):
    return hashlib.sha256(data).hexdigest()

def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")

def require(condition, message):
    if not condition:
        raise ValueError(message)

def walk(value, pointer=""):
    yield pointer, value
    if isinstance(value, dict):
        for key, item in value.items():
            yield from walk(item, pointer + "/" + key)
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from walk(item, pointer + "/" + str(index))

def contract(row, role):
    value = row[role]
    return value.get("completed_task_comparison_endpoint_contract") or (value.get("completion_contract") or {}).get("comparison_endpoint_contract")

def validation(counts):
    return {
        "detector_contracts": dict(counts),
        "all_available_quality_and_performance_contracts_match_runtime": True,
        "detector_thresholds": {"score_threshold": 0.25, "iou_threshold": 0.45, "max_detections": 300, "class_aware": True, "input_hw": [640, 640]},
        "threshold_note": "Comparison policy; NMS need not execute on integrated/NMS-free graphs. Runtime endpoint fields preserve physical distinction.",
        "energy": {"DeepX_configurations": 75, "command_windows": 225, "sample_rate_hz": 2000},
        "new_measurements": False,
        "old_admission_flags_reinterpreted": False,
    }

def reconstruct(archive, provenance):
    require(digest(archive.read_bytes()) == provenance["source_archive"]["sha256"], "Original archive SHA-256 differs")
    with zipfile.ZipFile(archive) as stream:
        members = {}
        for item in provenance["source_files"]:
            data = stream.read(item["archive_member"])
            require(digest(data) == item["sha256"] and len(data) == item["size_bytes"], "Source member changed: " + item["archive_member"])
            members[item["archive_member"]] = data
    rows = json.loads(gzip.decompress(members["analysis/audit_inputs/source_extracts.json.gz"]))
    counts = collections.Counter()
    endpoints, workloads = [], []
    for index, row in enumerate(rows):
        uid = row["uid"]
        task = "detection" if uid.split("|")[1] in MODELS else "classification"
        bindings = {key: row[key] for key in ["quality", "performance", "runtime"]}
        if task == "detection":
            quality = contract(row, "quality_row")
            performance = contract(row, "performance_row")
            runtime = contract(row, "runtime_row")
            require(bool(runtime), "Missing runtime contract: " + uid)
            if quality:
                require(quality == runtime, "Quality/runtime contract differs: " + uid)
            if performance:
                require(performance == runtime, "Performance/runtime contract differs: " + uid)
            counts["detector_rows"] += 1
            counts["explicit_quality_contracts"] += bool(quality)
            counts["explicit_performance_contracts"] += bool(performance)
            endpoints.append({
                "uid": uid, "source_row_index": index, "source_bindings": bindings,
                "quality_comparison_contract": quality, "performance_comparison_contract": performance,
                "runtime_comparison_contract": runtime,
                "quality_completed_endpoint": row["quality_row"].get("completed_task_endpoint_contract"),
                "runtime_completed_endpoint": row["runtime_row"].get("completed_task_endpoint_contract"),
                "quality_host_postprocess_required": row["quality_row"].get("host_postprocess_required"),
            })
        facts, seen = [], set()
        for pointer, value in walk(row):
            keep = False
            if isinstance(value, dict) and value.get("schema") == "onnx-splitpoint/image-preprocessing-contract":
                keep = True
            if pointer.endswith(("/validation_dataset_sha256", "/validation_dataset_ground_truth_sha256", "/validation_dataset_image_ids_sha256", "/trt_precision", "/execution_precision", "/full_runtime_precision", "/quality_runtime_precision", "/runtime_precision_identity")) and value not in [None, ""]:
                keep = True
            if isinstance(value, str) and ("val_by_wnid_n5000_s20260710" in value or "val2017_n5000_s20260710" in value) and len(value) < 2000:
                keep = True
            if keep:
                signature = json.dumps(value, sort_keys=True)
                if signature not in seen:
                    facts.append({"json_pointer": pointer, "value": value})
                    seen.add(signature)
        workloads.append({"uid": uid, "source_row_index": index, "task": task, "quality_source": row["quality"], "selected_facts": facts})
    independent = json.loads(members["analysis/audit_independent_inputs.json"])
    energy = []
    for index, row in enumerate(independent["rows"]):
        require(row["config_id"].split("|")[2] == "DeepX", "Unexpected energy setup")
        energy.append({"uid": row["config_id"], "source_row_index": index, "energy_summary": row["energy_summary"], "runs": [{"run_index": i, "window_manifest": value["window_manifest"], "window_manifest_source": value["window_manifest_source"]} for i, value in enumerate(row["runs"])]})
    quality_rows = []
    for index, row in enumerate(rows):
        if row["uid"] in CASE_UIDS:
            quality_rows.append({"uid": row["uid"], "source_row_index": index, "quality_source": row["quality"], "accuracy_gate_metrics": row["quality_row"].get("accuracy_gate_metrics"), "quality_identity": row["quality_row"].get("quality_identity"), "validation_dataset_sha256": row["quality_row"].get("validation_dataset_sha256"), "validation_dataset_image_ids_sha256": row["quality_row"].get("validation_dataset_image_ids_sha256"), "validation_dataset_ground_truth_sha256": row["quality_row"].get("validation_dataset_ground_truth_sha256")})
    return {
        "endpoint_contracts.csv": members["results/endpoint_contracts.csv"],
        "detector_endpoint_projection.json": encoded({"source": "analysis/audit_inputs/source_extracts.json.gz", "selection": "All 96 detector rows. Contracts and source bindings copied without modification; absent object stays null.", "rows": endpoints}),
        "workload_contract_projection.json": encoded({"source": "analysis/audit_inputs/source_extracts.json.gz", "selection": "All 450 rows. Selected explicit preprocessing objects, dataset identities/paths and precision fields. JSON pointers identify unchanged source values.", "rows": workloads}),
        "deepx_energy_window_projection.json": encoded({"source": "analysis/audit_independent_inputs.json", "scope": "75 DeepX Native configurations, 225 actual workload command windows. Does not attest sampling rate of other backends.", "rows": energy}),
        "yolov7_h8_quality_projection.json": encoded({"scope": "Existing configuration-versus-CPU-reference paired-bootstrap summary intervals, NOT split-versus-Full paired intervals. No per-image predictions or bootstrap replicate samples are present in these selected records.", "source": "analysis/audit_inputs/source_extracts.json.gz", "rows": quality_rows}),
        "VALIDATION.json": encoded(validation(counts)),
    }

def verify_values():
    endpoints = json.loads((ROOT / "detector_endpoint_projection.json").read_text())["rows"]
    counts = collections.Counter()
    hashes = collections.defaultdict(set)
    for row in endpoints:
        runtime = row["runtime_comparison_contract"]
        require(bool(runtime), "Missing runtime contract")
        for key, expected in [("score_threshold", 0.25), ("iou_threshold", 0.45), ("max_detections", 300), ("class_aware", True), ("input_hw", [640, 640]), ("coordinate_space", "original_image_xyxy_pixels"), ("output_record_format", "xyxy_score_class")]:
            require(runtime.get(key) == expected, "Unexpected comparison field: " + key)
        for role in ["quality_comparison_contract", "performance_comparison_contract"]:
            if row[role]:
                require(row[role] == runtime, "Available contract differs: " + row["uid"])
        counts["detector_rows"] += 1
        counts["explicit_quality_contracts"] += bool(row["quality_comparison_contract"])
        counts["explicit_performance_contracts"] += bool(row["performance_comparison_contract"])
        hashes[row["uid"].split("|")[1]].add(runtime["endpoint_contract_hash"])
    require(dict(counts) == {"detector_rows": 96, "explicit_quality_contracts": 65, "explicit_performance_contracts": 52}, "Endpoint coverage differs")
    require(len(hashes) == 4 and all(len(value) == 1 for value in hashes.values()), "Model comparison hashes differ")
    require((ROOT / "VALIDATION.json").read_bytes() == encoded(validation(counts)), "Validation summary differs")
    workload = json.loads((ROOT / "workload_contract_projection.json").read_text())["rows"]
    require(len(workload) == 450 and len({row["uid"] for row in workload}) == 450, "Workload coverage differs")
    require(collections.Counter(row["task"] for row in workload) == {"classification": 354, "detection": 96}, "Task counts differ")
    explicit_preprocessing = collections.Counter()
    for row in workload:
        if any(isinstance(fact["value"], dict) and fact["value"].get("schema") == "onnx-splitpoint/image-preprocessing-contract" for fact in row["selected_facts"]):
            explicit_preprocessing[row["task"]] += 1
    require(explicit_preprocessing == {"classification": 298, "detection": 87}, "Preprocessing-object coverage differs")
    energy = json.loads((ROOT / "deepx_energy_window_projection.json").read_text())["rows"]
    require(len(energy) == 75 and sum(len(row["runs"]) for row in energy) == 225, "Energy coverage differs")
    for row in energy:
        require(row["uid"].split("|")[2] == "DeepX", "Unexpected energy setup")
        for run in row["runs"]:
            require(run["window_manifest"]["sample_rate_hz"] == 2000, "Workload sampling rate differs")
    quality = json.loads((ROOT / "yolov7_h8_quality_projection.json").read_text())["rows"]
    require({row["uid"] for row in quality} == CASE_UIDS, "Case-study quality identities differ")
    for row in quality:
        metrics = row["accuracy_gate_metrics"]
        require(metrics["n"] == 5000 and abs(metrics["delta"] - (metrics["candidate"] - metrics["reference"])) < 1e-12, "CPU-relative quality identity differs")
    return {"detectors": len(endpoints), "workloads": len(workload), "energy_configurations": len(energy), "energy_windows": 225, "case_quality_rows": len(quality)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Optional original SM2 result ZIP for byte-exact reconstruction in memory")
    parser.add_argument("--check-only", action="store_true", help="Read-only verification (also the default)")
    args = parser.parse_args()
    provenance = json.loads((ROOT / "SOURCE_PROVENANCE.json").read_text())
    for item in provenance["bundled_files"]:
        payload = (ROOT / item["file"]).read_bytes()
        require(len(payload) == item["size_bytes"] and digest(payload) == item["sha256"], "Bundled file differs: " + item["file"])
    generator = provenance["generator"]
    require(generator["file"] == Path(__file__).name and digest(Path(__file__).read_bytes()) == generator["sha256"], "Generator hash differs")
    values = verify_values()
    reconstructed = 0
    if args.archive:
        for name, payload in reconstruct(args.archive, provenance).items():
            require(payload == (ROOT / name).read_bytes(), "Reconstructed bytes differ: " + name)
            reconstructed += 1
    print(json.dumps({"status": "PASS", "mode": "read_only", "hashed_files": len(provenance["bundled_files"]), "generator_verified": True, "value_checks": values, "archive_reconstructed_files": reconstructed, "new_hardware_or_quality_runs": False}, indent=2))

if __name__ == "__main__":
    main()
