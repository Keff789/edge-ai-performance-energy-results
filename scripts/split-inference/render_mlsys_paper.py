#!/usr/bin/env python3
"""Render MLSys paper figures from the existing offline dataset.

This presentation-only entry point uses the established publication calculations
and a common statistical-figure style. It does not change the frozen R22 profile,
run measurements, or fit models. The conceptual runner schematic remains a
separate illustration and keeps its original sans-serif labels.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import sys
import tempfile

SCRIPT_ROOT = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_ROOT.parents[1]
sys.path.insert(0, str(SCRIPT_ROOT))

from publication_mlsys_data import build
from publication_mlsys_figures import PAPER_STYLE, render


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--data-root', type=Path,
                        default=REPO_ROOT / 'results/split-inference')
    parser.add_argument('--verify', action='store_true',
                        help='Require exact agreement with the frozen R22 figure data')
    args = parser.parse_args()
    output, data_root = args.output.resolve(), args.data_root.resolve()
    if output.exists() and any(output.iterdir()):
        parser.error('Use an empty output directory')
    output.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault('MPLCONFIGDIR', str(output.parent / '.mlsys-paper-mpl-cache'))

    # The shared builder also writes tables. They are temporary here because
    # this entry point only exports figures and their numerical payloads.
    with tempfile.TemporaryDirectory(prefix='.figure-context-', dir=output) as temp:
        context = build(REPO_ROOT, data_root, Path(temp))
    _, payload = render(output, context, uniform_typography=True)

    actual = output / 'figures/FIGURE_DATA.json'
    reference = REPO_ROOT / 'results/split-inference/publications/mlsys-r22/figures/FIGURE_DATA.json'
    exact = actual.read_bytes() == reference.read_bytes()
    if args.verify and not exact:
        raise ValueError('Generated figure data differ from the frozen R22 reference')

    source_files = {file for figure in payload.values() for file in figure['input_files']}
    source_files.update({
        'scripts/split-inference/render_mlsys_paper.py',
        'scripts/split-inference/publication_mlsys_data.py',
        'scripts/split-inference/publication_mlsys_figures.py',
    })
    provenance = {
        'schema': 'mlsys-r25-presentation-v1',
        'generator': 'scripts/split-inference/render_mlsys_paper.py',
        'python': platform.python_version(),
        'uniform_statistical_typography': True,
        'paper_style': PAPER_STYLE,
        'measurement_changes': False,
        'figure_data_equal_to_r22': exact,
        'figure_data_sha256': digest(actual),
        'data_inputs': {name: digest(data_root / name) for name in
                        ['data/PAPER_DATASET.json', 'data/analysis_config.json']},
        'source_sha256': {name: digest(REPO_ROOT / name) for name in sorted(source_files)},
        'output_sha256': {str(path.relative_to(output)): digest(path)
                          for path in sorted((output / 'figures').iterdir()) if path.is_file()},
    }
    (output / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2, sort_keys=True) + '\n')
    (output / 'README.md').write_text('''# MLSys R25 figure presentation

These figures use the existing MLSys publication calculations and a common
STIXGeneral style for statistical plots. The numerical figure payload is
unchanged from the frozen R22 profile. No measurements, selections, quality
filters or calibration fits are added or changed.

The conceptual `system_overview` retains its original sans-serif labels. The
current manuscript uses the separately maintained vector illustration under
`publications/mlsys/figure1/`. Its replacement is not part of this renderer.
The current RQ2 shortlist and per-device Generic figures are generated by
`scripts/supplementary-studies/rq2-all-cuts-20261020/reproduce.py`, which imports
the same paper style. Their outputs are in the corresponding study directory.

From the repository root, with the split-inference plotting dependencies:

```sh
python -I -B scripts/split-inference/render_mlsys_paper.py \\
  --output /tmp/mlsys-paper-figures --verify
```

Use an empty output directory. The command reads the existing canonical offline
dataset, renders PDF/SVG/PNG files, and exports all plotted coordinates and input
identities. `--verify` requires byte-identical numerical figure data against R22.
The conceptual schematic and historical graph-rule heatmap retain their own
documented scope. `PROVENANCE.json` records input, source and output hashes.
The original R22 entry point and outputs remain unchanged.
''')
    print(json.dumps({'output': str(output), 'figure_count': len(payload),
                      'figure_data_equal_to_r22': exact,
                      'figure_data_sha256': provenance['figure_data_sha256']}, indent=2))


if __name__ == '__main__':
    main()
